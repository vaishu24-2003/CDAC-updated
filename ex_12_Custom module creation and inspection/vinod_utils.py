def is_even(n):
    """Returns True if number is even, otherwise False."""
    return n % 2 == 0


def square(n):
    """Returns square of a number."""
    return n * n


def cube(n):
    """Returns cube of a number."""
    return n * n * n


def format_city(city):
    """Returns city name in title case format."""
    return city.title()
